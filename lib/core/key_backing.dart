/// What is actually holding the wallet's unlock keys.
///
/// **This exists so a screen can state a fact instead of a reassurance.** The
/// keystore code has always chosen the strongest thing the phone offers and
/// fallen back quietly — StrongBox, then the TEE, then whatever the platform
/// will give — and until now nothing reported which of those happened. A wallet
/// that says "your keys are protected by hardware" without knowing is making a
/// claim about somebody's money on the strength of a code path it did not
/// check, and this project has shipped a signal that was wired up and
/// permanently null before.
library;

/// Where a key lives, strongest first.
///
/// The order is load-bearing: [weakest] reduces over it, because a summary that
/// took the *best* of two keys would name StrongBox on a phone where one of
/// them is only TEE-backed.
enum KeyBacking {
  /// A separate security chip — Android's StrongBox, Apple's Secure Enclave.
  /// The key is generated and used on silicon the main processor cannot read,
  /// so even a rooted operating system cannot lift it out.
  strongBox,

  /// The phone's secure processor. The key is still one the app can use and
  /// cannot read, which is the property that matters; it just shares silicon
  /// with everything else.
  hardware,

  /// No hardware backing. The operating system is the whole protection.
  software,

  /// Nothing to report — the key has not been created, or the platform refused
  /// to say. **Never rendered as "protected"**: this is the answer that must
  /// stay distinguishable from [software], because "we did not look" and "we
  /// looked and it is software" are different statements.
  unknown;

  static KeyBacking parse(String? raw) => switch (raw) {
        'strongbox' => KeyBacking.strongBox,
        'hardware' => KeyBacking.hardware,
        'software' => KeyBacking.software,
        _ => KeyBacking.unknown,
      };

  /// True when the key is in secure hardware of either kind.
  ///
  /// **What that promises differs by kind**, and the wording on screen follows
  /// it: a separate chip is claimed to hold against root; the phone's secure
  /// processor is claimed to keep the key from the app, and nothing about root
  /// is said for it.
  bool get isHardware =>
      this == KeyBacking.strongBox || this == KeyBacking.hardware;
}

/// One key in the platform's store, as it reports itself.
class KeyStoreReport {
  /// Whether the alias currently holds a key. False is ordinary rather than
  /// broken: it means quick unlock or the PIN has never been armed, and the
  /// platform deliberately does not create one to answer a question about it.
  final bool exists;

  final KeyBacking backing;

  /// Whether the platform distinguished *which* secure hardware.
  ///
  /// Android below API 31 answers a bare "inside secure hardware or not", so a
  /// phone with a real StrongBox chip and one with only a TEE are the same
  /// answer. False means [backing] is a floor, not a measurement.
  final bool precise;

  const KeyStoreReport({
    required this.exists,
    required this.backing,
    required this.precise,
  });

  /// The answer for a platform with no handler at all — iOS before this was
  /// built, a test binary, a desktop build.
  const KeyStoreReport.unknown()
      : exists = false,
        backing = KeyBacking.unknown,
        precise = false;

  factory KeyStoreReport.fromPlatform(Map<Object?, Object?>? raw) {
    if (raw == null) return const KeyStoreReport.unknown();
    final exists = raw['exists'] == true;
    return KeyStoreReport(
      exists: exists,
      // A key that does not exist has no backing, whatever the platform put in
      // the field. Trusting the string here would let a stale or padded reply
      // report protection for a key nobody has.
      backing: exists ? KeyBacking.parse(raw['backing'] as String?) : KeyBacking.unknown,
      precise: exists && raw['precise'] == true,
    );
  }
}

/// Both keys, reduced to what may honestly be said about the pair.
///
/// The wallet holds two: the one released by the system gate, which stands
/// behind quick unlock, and the device-bound one the PIN sits on. They are
/// generated by the same code and normally land in the same place — but not
/// always, because only the first can be refused for reasons to do with the
/// person's enrolled biometrics.
class SecurityKeyReport {
  /// Behind quick unlock. Released by a fingerprint or the phone's own code.
  final KeyStoreReport unlockKey;

  /// Behind the PIN. Bound to this phone and gated by nothing, which is what
  /// makes six digits worth more than six digits.
  final KeyStoreReport pinKey;

  const SecurityKeyReport({required this.unlockKey, required this.pinKey});

  const SecurityKeyReport.unknown()
      : unlockKey = const KeyStoreReport.unknown(),
        pinKey = const KeyStoreReport.unknown();

  Iterable<KeyStoreReport> get _present =>
      [unlockKey, pinKey].where((k) => k.exists);

  /// Whether anything is armed at all. False means the password is the only
  /// door, which is a complete answer and not a failure.
  bool get anyKey => _present.isNotEmpty;

  /// **The weakest of the keys that exist**, because the summary describes the
  /// wallet rather than its best part. If a phone put the PIN's key in
  /// StrongBox and the unlock key in software, "StrongBox" would be true of one
  /// key and false of the wallet.
  /// A key that exists and will not say what holds it makes the *pair*
  /// unknown, which is why [KeyBacking.unknown] sits last in the enum rather
  /// than first: "we could not tell" has to outrank every answer it might have
  /// been, or the summary quietly promises the better one.
  KeyBacking get backing {
    KeyBacking? worst;
    for (final key in _present) {
      if (worst == null || key.backing.index > worst.index) worst = key.backing;
    }
    return worst ?? KeyBacking.unknown;
  }

  /// True only when every key that exists was measured rather than inferred.
  /// One imprecise key makes the summary imprecise — the screen has to say so,
  /// or it states a chip the phone never named.
  bool get precise => anyKey && _present.every((k) => k.precise);
}
